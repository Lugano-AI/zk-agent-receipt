//! Regenerate the canonical P128Pow5T3 tables used by the zkVM backend.
//!
//! Run from the workspace root:
//! `cargo +risc0 run --target aarch64-apple-darwin -p relation --bin
//! generate_poseidon_constants > relation/src/poseidon_constants.rs`

use halo2_poseidon::{P128Pow5T3, Spec};
use pasta_curves::{
    group::ff::PrimeField,
    pallas,
};

type Fp = pallas::Base;

fn canonical_limbs(value: Fp) -> [u32; 8] {
    let repr = value.to_repr();
    let bytes = repr.as_ref();
    core::array::from_fn(|index| {
        u32::from_le_bytes(
            bytes[index * 4..index * 4 + 4]
                .try_into()
                .expect("Pallas encoding has 32 bytes"),
        )
    })
}

fn emit_limb(limbs: [u32; 8]) {
    print!("[");
    for (index, limb) in limbs.into_iter().enumerate() {
        if index != 0 {
            print!(", ");
        }
        print!("0x{limb:08x}");
    }
    println!("],");
}

fn main() {
    let (round_constants, mds, _) = <P128Pow5T3 as Spec<Fp, 3, 2>>::constants();

    println!("//! Canonical little-endian Pallas limbs for `halo2_poseidon` 0.2.0 `P128Pow5T3`.");
    println!("//!");
    println!("//! Generated by `cargo +risc0 run --target aarch64-apple-darwin -p relation --bin");
    println!("//! generate_poseidon_constants > relation/src/poseidon_constants.rs`.");
    println!("//! Do not edit by hand: the native `embedded_poseidon_constants_match_spec` test");
    println!("//! compares these tables with `Spec::constants()`.");
    println!();
    println!("pub(crate) const ROUND_CONSTANTS: [[[u32; 8]; 3]; 64] = [");
    for row in round_constants {
        println!("    [");
        for value in row {
            print!("        ");
            emit_limb(canonical_limbs(value));
        }
        println!("    ],");
    }
    println!("];");
    println!();
    println!("pub(crate) const MDS: [[[u32; 8]; 3]; 3] = [");
    for row in mds {
        println!("    [");
        for value in row {
            print!("        ");
            emit_limb(canonical_limbs(value));
        }
        println!("    ],");
    }
    println!("];");
}
